create function public.is_approved()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and status = 'approved'
  );
$$;

create function public.current_role()
returns public.user_role
language sql
stable
security definer
set search_path = public
as $$
  select role
  from public.profiles
  where id = auth.uid();
$$;

create function public.current_chapter()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
  select chapter_id
  from public.profiles
  where id = auth.uid();
$$;

create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  new_full_name text;
  new_chapter_id uuid;
begin
  new_full_name := nullif(btrim(new.raw_user_meta_data ->> 'full_name'), '');
  if new_full_name is null then
    raise exception 'full_name is required' using errcode = '23502';
  end if;

  if new.raw_user_meta_data ->> 'terms_accepted' is distinct from 'true' then
    raise exception 'terms must be accepted before signup' using errcode = '23514';
  end if;

  new_chapter_id := nullif(new.raw_user_meta_data ->> 'chapter_id', '')::uuid;

  insert into public.profiles (
    id,
    full_name,
    chapter_id,
    position,
    role,
    status,
    terms_accepted_at,
    guardian_consent_at
  )
  values (
    new.id,
    new_full_name,
    new_chapter_id,
    nullif(btrim(new.raw_user_meta_data ->> 'position'), ''),
    'member',
    'pending',
    now(),
    case
      when new.raw_user_meta_data ->> 'guardian_consent' = 'true' then now()
      else null
    end
  );

  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create function public.protect_profile_fields()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if public.current_role() is distinct from 'admin'::public.user_role
    and (
      new.role is distinct from old.role
      or new.status is distinct from old.status
      or new.chapter_id is distinct from old.chapter_id
    )
  then
    raise exception 'only admins may change profile role, status, or chapter'
      using errcode = '42501';
  end if;

  return new;
end;
$$;

create trigger protect_profile_fields
before update on public.profiles
for each row execute function public.protect_profile_fields();

create function public.write_audit_log()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  changed_record_id text;
begin
  if tg_op = 'DELETE' then
    changed_record_id := old.id::text;
  else
    changed_record_id := new.id::text;
  end if;

  insert into public.audit_log (actor_id, action, table_name, record_id)
  values (auth.uid(), tg_op, tg_table_name, changed_record_id);

  if tg_op = 'DELETE' then
    return old;
  end if;

  return new;
end;
$$;

create trigger audit_submissions
after insert or update of score, status or delete on public.submissions
for each row execute function public.write_audit_log();

create trigger audit_profiles
after insert or update of role, status or delete on public.profiles
for each row execute function public.write_audit_log();
