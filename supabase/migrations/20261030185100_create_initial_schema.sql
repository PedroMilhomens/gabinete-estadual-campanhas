create type public.user_status as enum ('pending', 'approved', 'rejected');
create type public.user_role as enum ('member', 'reviewer', 'admin');
create type public.submission_status as enum ('draft', 'submitted', 'returned', 'approved');

create table public.chapters (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  number integer,
  city text
);

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text not null,
  chapter_id uuid references public.chapters (id),
  position text,
  role public.user_role not null default 'member',
  status public.user_status not null default 'pending',
  terms_accepted_at timestamptz,
  guardian_consent_at timestamptz,
  created_at timestamptz not null default now()
);

create table public.campaigns (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  starts_at date,
  ends_at date,
  active boolean not null default true
);

create table public.activities (
  id uuid primary key default gen_random_uuid(),
  campaign_id uuid references public.campaigns (id),
  name text not null,
  description text,
  points integer check (points >= 0),
  due_at timestamptz
);

create table public.submissions (
  id uuid primary key default gen_random_uuid(),
  activity_id uuid references public.activities (id),
  chapter_id uuid references public.chapters (id),
  submitted_by uuid references public.profiles (id),
  description text check (char_length(description) <= 5000),
  status public.submission_status not null default 'draft',
  score integer check (score >= 0),
  reviewed_by uuid references public.profiles (id),
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  unique (activity_id, chapter_id)
);

create table public.attachments (
  id uuid primary key default gen_random_uuid(),
  submission_id uuid references public.submissions (id) on delete cascade,
  storage_path text not null,
  mime text not null,
  size_bytes integer not null check (size_bytes between 0 and 5242880)
);

create table public.comments (
  id uuid primary key default gen_random_uuid(),
  submission_id uuid references public.submissions (id) on delete cascade,
  author_id uuid references public.profiles (id),
  body text check (char_length(body) <= 2000),
  created_at timestamptz not null default now()
);

create table public.audit_log (
  id bigint generated by default as identity primary key,
  actor_id uuid,
  action text,
  table_name text,
  record_id text,
  created_at timestamptz not null default now()
);

